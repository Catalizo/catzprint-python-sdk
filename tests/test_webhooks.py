"""Webhook verification against vectors produced by the Go server's SignWebhook.

The vectors were generated by running SignWebhook from
server/internal/core/webhooks.go (copied verbatim into a tiny Go program).
"""

from __future__ import annotations

import pytest

from catzprint import CatzPrint, SignatureVerificationError, WebhookEvent, construct_event, webhooks

GO_VECTORS = [
    (
        "whsec_test_secret_123",
        1791796443,
        '{"created_at":"2026-10-12T09:14:03Z","data":{"job":{"id":"6f1c2a7e-0000-4000-8000-000000000001",'
        '"status":"printed","reference":"order-1042"}},"org_id":"9b2f0000-0000-4000-8000-000000000000",'
        '"type":"job.printed"}',
        "t=1791796443,v1=283950b0f45b0dff0896d72d652cce05b4588704b0f248b12e6d23650bb06909",
    ),
    (
        "whsec_AbCdEf0123456789AbCdEf0123456789AbCd",
        1700000000,
        '{"created_at":"2023-11-14T22:13:20Z","data":{"message":"Test event from CatzPrint"},'
        '"org_id":"34c4671b-d2ab-4ddf-aaac-615786d5acac","type":"ping"}',
        "t=1700000000,v1=cbd9ae50413032fba4539120eb990349acad1e4256847cd45d400a0c4976c96c",
    ),
    (
        "whsec_unicode",
        1760000000,
        '{"data":{"job":{"title":"Café ☕ receipt"}},"type":"job.created"}',
        "t=1760000000,v1=cad486033dcaeaa327a1010b6c1a9b2b5aa5a126bf9eaf26fb8d8cc68052198d",
    ),
]


@pytest.mark.parametrize("secret,ts,body,header", GO_VECTORS)
def test_sign_matches_go(secret: str, ts: int, body: str, header: str) -> None:
    assert webhooks.sign(body, secret, ts) == header
    assert webhooks.sign(body.encode("utf-8"), secret, ts) == header


@pytest.mark.parametrize("secret,ts,body,header", GO_VECTORS)
def test_verify_valid(secret: str, ts: int, body: str, header: str) -> None:
    ev = webhooks.verify(body.encode("utf-8"), header, secret, now=ts + 10)
    assert isinstance(ev, WebhookEvent)
    assert ev.raw["type"] == ev.type
    # str payload works too
    assert webhooks.verify(body, header, secret, now=ts).type == ev.type


def test_event_fields() -> None:
    secret, ts, body, header = GO_VECTORS[0]
    ev = construct_event(body, header, secret, now=ts)
    assert ev.type == "job.printed" and ev.org_id.startswith("9b2f")
    assert ev.job is not None and ev.job.reference == "order-1042" and ev.job.status == "printed"
    assert ev.created_at is not None and ev.created_at.year == 2026


def test_tampered_body() -> None:
    secret, ts, body, header = GO_VECTORS[0]
    with pytest.raises(SignatureVerificationError, match="match"):
        webhooks.verify(body.replace("order-1042", "order-1043"), header, secret, now=ts)


def test_tampered_signature_and_timestamp() -> None:
    secret, ts, body, header = GO_VECTORS[1]
    bad = header[:-1] + ("0" if header[-1] != "0" else "1")
    with pytest.raises(SignatureVerificationError):
        webhooks.verify(body, bad, secret, now=ts)
    shifted = header.replace(f"t={ts}", f"t={ts + 1}")
    with pytest.raises(SignatureVerificationError):
        webhooks.verify(body, shifted, secret, now=ts)


def test_expired_and_future() -> None:
    secret, ts, body, header = GO_VECTORS[0]
    with pytest.raises(SignatureVerificationError, match="tolerance"):
        webhooks.verify(body, header, secret, now=ts + 301)
    with pytest.raises(SignatureVerificationError, match="tolerance"):
        webhooks.verify(body, header, secret, now=ts - 301)
    assert webhooks.verify(body, header, secret, now=ts + 300).type == "job.printed"
    assert webhooks.verify(body, header, secret, now=ts + 10_000, tolerance=None).type == "job.printed"
    with pytest.raises(SignatureVerificationError):
        webhooks.verify(body, header, secret, now=ts + 61, tolerance=60)


def test_wrong_secret() -> None:
    _, ts, body, header = GO_VECTORS[0]
    with pytest.raises(SignatureVerificationError):
        webhooks.verify(body, header, "whsec_wrong", now=ts)


def test_multiple_v1_entries_and_secrets() -> None:
    secret, ts, body, header = GO_VECTORS[0]
    good = header.split("v1=")[1]
    multi = f"t={ts},v1={'0' * 64},v1={good}"
    assert webhooks.verify(body, multi, secret, now=ts).type == "job.printed"
    assert webhooks.verify(body, f" t={ts} , v1={good.upper()} ", secret, now=ts).type == "job.printed"
    # rotating secrets: any of them may match
    assert webhooks.verify(body, header, ["whsec_new", secret], now=ts).type == "job.printed"


@pytest.mark.parametrize("header", [None, "", "garbage", "t=abc,v1=00", "v1=00", "t=1791796443"])
def test_malformed_headers(header: object) -> None:
    secret, ts, body, _ = GO_VECTORS[0]
    with pytest.raises(SignatureVerificationError):
        webhooks.verify(body, header, secret, now=ts)  # type: ignore[arg-type]


def test_empty_secret_rejected() -> None:
    _, ts, body, header = GO_VECTORS[0]
    with pytest.raises(SignatureVerificationError):
        webhooks.verify(body, header, "", now=ts)


def test_non_json_payload_after_valid_signature() -> None:
    header = webhooks.sign(b"not json", "s", 100)
    with pytest.raises(SignatureVerificationError, match="JSON"):
        webhooks.verify(b"not json", header, "s", now=100)


def test_client_webhooks_namespace() -> None:
    secret, ts, body, header = GO_VECTORS[2]
    c = CatzPrint("cz_test_x", base_url="http://127.0.0.1:9")
    assert c.webhooks.verify(body, header, secret, now=ts).data["job"]["title"] == "Café ☕ receipt"
    assert c.webhooks.construct_event(body, header, secret, now=ts).type == "job.created"
    c.close()


def test_non_ascii_signature_is_rejected_cleanly() -> None:
    header = "t=1700000000,v1=é" + "a" * 63
    with pytest.raises(SignatureVerificationError):
        webhooks.verify_signature("{}", header, "whsec_x", now=1700000000)


def test_huge_timestamp_is_rejected_cleanly() -> None:
    header = "t=" + "9" * 5000 + ",v1=" + "0" * 64
    with pytest.raises(SignatureVerificationError):
        webhooks.verify_signature("{}", header, "whsec_x")


def test_nan_tolerance_keeps_replay_check() -> None:
    header = webhooks.sign("{}", "whsec_x", timestamp=1000)
    with pytest.raises(SignatureVerificationError):
        webhooks.verify_signature("{}", header, "whsec_x", tolerance=float("nan"), now=100_000)


def test_event_id() -> None:
    body = '{"id":"dlv_01HZX","type":"ping","created_at":"2026-10-17T00:00:00Z","org_id":"o","data":{}}'
    ev = webhooks.verify(body, webhooks.sign(body, "whsec_x"), "whsec_x")
    assert ev.id == "dlv_01HZX"
    old = '{"type":"ping","created_at":"2026-10-17T00:00:00Z","org_id":"o","data":{}}'
    assert webhooks.verify(old, webhooks.sign(old, "whsec_x"), "whsec_x").id is None
